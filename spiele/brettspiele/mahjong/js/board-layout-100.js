// Schwer: elf neue Umrisse, je vier Höhenprofile = 44 Felder (57-100).
function ergaenzeSchwereSammlung(sammlung, umrisse, breite, hoechste, startLevel) {
    let level = startLevel;

    umrisse.forEach(([name, bild]) => {
        SCHWER_PROFIL_FOLGE.forEach(profilName => {
            sammlung[level] = schwerForm(level, name, bild, profilName, breite, hoechste);
            level++;
        });
    });

    return sammlung;
}

