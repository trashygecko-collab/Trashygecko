let pechVorrat = [];
let letzterPech = "";

// Zieht einen Spruch, ohne dass sich einer direkt wiederholt. Erst wenn alle
// Sprueche durch sind, wird neu gemischt.
function pechSpruch() {
    if (pechVorrat.length === 0) {
        pechVorrat = PECH_SPRUECHE.slice();

        for (let i = pechVorrat.length - 1; i > 0; i--) {
            const j = Math.floor(Math.random() * (i + 1));
            [pechVorrat[i], pechVorrat[j]] = [pechVorrat[j], pechVorrat[i]];
        }
    }

    let spruch = pechVorrat.pop();

    if (spruch === letzterPech && pechVorrat.length > 0) {
        const tausch = pechVorrat.pop();
        pechVorrat.push(spruch);
        spruch = tausch;
    }

    letzterPech = spruch;

    return spruch;
}
