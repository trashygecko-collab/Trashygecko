// Reine Mahjong-Sprüche (Steine, Paare, Zwillinge) bleiben dem Mahjong-Spiel
// vorbehalten. Allgemeine Spiele rufen pechSpruch(true) und bekommen nur die
// übrigen Sprüche; ohne Argument bleibt die ganze Liste.
const PECH_MAHJONG = /mahjong|ziegel|bambus|zwilling|gegenstück|traumpaar|paarweise|pärchen|\bpaare?\b|paaren\b/i;
const PECH_ALLGEMEIN = /in stein gemeißelt|meilenstein|grabstein|stolperstein|stein-?gut|steinig|steinstark|steinzeit|einstein|legosteine|ins rollen|stein im brett|stein der weisen|stein des anstoßes|stein und bein|stein auf stein|stein vom herzen/i;

function istMahjongPech(text) {
    if (PECH_MAHJONG.test(text)) return true;

    return /stein/i.test(text) && !PECH_ALLGEMEIN.test(text);
}

let pechVorrat = [];
let pechQuelle = null;
let pechAllgemein = null;
let letzterPech = "";

// Zieht einen Spruch, ohne dass sich einer direkt wiederholt. Erst wenn alle
// Sprueche durch sind, wird neu gemischt.
function pechSpruch(ohneMahjong) {
    const quelle = ohneMahjong
        ? (pechAllgemein || (pechAllgemein = PECH_SPRUECHE.filter((t) => !istMahjongPech(t))))
        : PECH_SPRUECHE;

    if (pechQuelle !== quelle || pechVorrat.length === 0) {
        pechQuelle = quelle;
        pechVorrat = quelle.slice();

        for (let i = pechVorrat.length - 1; i > 0; i--) {
            const j = Math.floor(Math.random() * (i + 1));
            [pechVorrat[i], pechVorrat[j]] = [pechVorrat[j], pechVorrat[i]];
        }
    }

    let spruch = pechVorrat.pop();

    if (spruch === letzterPech && pechVorrat.length > 0) {
        const tausch = pechVorrat.pop();
        pechVorrat.push(spruch);
        spruch = tausch;
    }

    letzterPech = spruch;

    return spruch;
}
